package com.jantursky.kascii.components

/** The two hand drawn block fonts. */
public enum class AsciiBigFont(
    internal val rows: Int,
) {
    /** Five rows tall, solid blocks. Letters, digits and basic punctuation. */
    Tall(5),

    /** Three rows tall, drawn with box characters. */
    Compact(3),
}

internal fun AsciiBigFont.glyphs(): Map<Char, List<String>> =
    when (this) {
        AsciiBigFont.Tall -> TALL
        AsciiBigFont.Compact -> COMPACT
    }

/** A five row glyph from `#` and `.` pixels. */
private fun tall(vararg rows: String): List<String> = rows.map { it.replace('#', '█').replace('.', ' ') }

